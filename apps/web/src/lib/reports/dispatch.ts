import { DISPATCH_STATES, formatInt } from "@tobacco/shared";
import { humanise, inRange, userNameOf } from "./helpers";
import type { ReportDef, ReportResult } from "./types";

export const dispatchReport: ReportDef = {
  slug: "dispatch",
  title: "Dispatch report",
  description: "Dispatch notes: destination warehouse, truck and driver, bale count and mass, status and cancellation reasons.",
  area: "Dispatch",
  filters: ["date", "status"],
  statusLabel: "Dispatch state",
  statusOptions: DISPATCH_STATES.map((s) => ({ value: s, label: humanise(s) })),
  run(db, f): ReportResult {
    const notes = db.dispatchNotes
      .filter((d) => inRange(d.createdAt, f) && (!f.status || d.state === f.status))
      .sort((a, b) => b.createdAt.localeCompare(a.createdAt));
    const rows = notes.map((d) => ({
      reference: d.ref,
      destination: db.warehouses.find((w) => w.code === d.warehouseCode)?.name ?? d.warehouseCode,
      truck: d.truckReg ?? null,
      driver: d.driver ?? null,
      bales: d.totalBales,
      mass: d.totalMass,
      state: d.state,
      created: d.createdAt,
      dispatched: d.dispatchDate ?? null,
      by: userNameOf(db, d.createdBy),
      cancelReason: d.cancelReason ?? null,
    }));
    const posted = notes.filter((d) => d.state === "POSTED");
    return {
      columns: [
        { key: "reference", header: "Reference", format: "mono" },
        { key: "destination", header: "Destination" },
        { key: "truck", header: "Truck", format: "mono" },
        { key: "driver", header: "Driver" },
        { key: "bales", header: "Bales", format: "int", align: "right" },
        { key: "mass", header: "Mass", format: "mass", align: "right" },
        { key: "state", header: "State", format: "status", statusKind: "dispatch" },
        { key: "created", header: "Created", format: "datetime" },
        { key: "dispatched", header: "Dispatch date", format: "date" },
        { key: "by", header: "Created by" },
        { key: "cancelReason", header: "Cancel reason" },
      ],
      rows,
      tiles: [
        { label: "Dispatch notes", value: formatInt(rows.length) },
        { label: "Posted", value: formatInt(posted.length) },
        { label: "Bales dispatched", value: formatInt(posted.reduce((a, d) => a + d.totalBales, 0)), hint: "posted notes" },
        { label: "Mass dispatched", value: `${posted.reduce((a, d) => a + d.totalMass, 0).toLocaleString("en-US")} kg` },
      ],
      notes: ["Posted dispatch notes are never deleted; drafts are cancelled with a reason (Manual 09)."],
    };
  },
};

export const shipmentReport: ReportDef = {
  slug: "shipment",
  title: "Shipment report",
  description: "Warehouse shipment files generated from posted dispatch notes.",
  area: "Dispatch",
  filters: ["date"],
  run(db, f): ReportResult {
    const files = db.shipmentExports.filter((s) => inRange(s.generatedAt, f)).sort((a, b) => b.generatedAt.localeCompare(a.generatedAt));
    const rows = files.map((s) => {
      const note = db.dispatchNotes.find((d) => d.id === s.dispatchNoteId);
      return {
        filename: s.filename,
        reference: note?.ref ?? null,
        destination: note ? (db.warehouses.find((w) => w.code === note.warehouseCode)?.name ?? note.warehouseCode) : null,
        generatedAt: s.generatedAt,
        by: userNameOf(db, s.generatedBy),
        lines: s.rowCount,
        format: s.isMockFormat ? "Demo layout (UQ-12)" : "Warehouse layout",
      };
    });
    return {
      columns: [
        { key: "filename", header: "File", format: "mono" },
        { key: "reference", header: "Dispatch note", format: "mono" },
        { key: "destination", header: "Destination" },
        { key: "generatedAt", header: "Generated", format: "datetime" },
        { key: "by", header: "Generated by" },
        { key: "lines", header: "Lines", format: "int", align: "right" },
        { key: "format", header: "Format" },
      ],
      rows,
      tiles: [
        { label: "Shipment files", value: formatInt(rows.length) },
        { label: "Bale lines", value: formatInt(rows.reduce((a, r) => a + r.lines, 0)) },
      ],
      notes: ["The warehouse shipment-file columns are not documented in the manuals; the demo layout is a placeholder (UQ-12)."],
    };
  },
};
