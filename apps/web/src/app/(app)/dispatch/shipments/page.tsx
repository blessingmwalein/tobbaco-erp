"use client";

import { useState } from "react";
import { Eye, FileDown, Warehouse } from "lucide-react";
import {
  Badge,
  Button,
  Callout,
  DataTable,
  Dialog,
  DialogBody,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
  PageHeader,
  type ColumnDef,
} from "@tobacco/ui";
import { formatDateTime, type ShipmentExport } from "@tobacco/shared";
import { RequirePermission } from "@/components/page-guard";
import { DispatchLink } from "@/components/domain/entity-links";
import { downloadTextFile } from "@/lib/csv";
import { useDbQuery } from "@/mock/hooks";
import { userName } from "@/mock/ctx";

interface Row {
  export: ShipmentExport;
  ref: string;
  warehouse: string;
  generatedByName: string;
}

export default function ShipmentFilesPage() {
  const { data, isLoading } = useDbQuery(["dispatch", "shipments"], (db): Row[] =>
    db.shipmentExports.map((e) => {
      const note = db.dispatchNotes.find((n) => n.id === e.dispatchNoteId);
      return { export: e, ref: note?.ref ?? e.dispatchNoteId, warehouse: note?.warehouseCode ?? "—", generatedByName: userName(db, e.generatedBy) };
    }),
  );
  const [preview, setPreview] = useState<ShipmentExport | null>(null);

  const columns: ColumnDef<Row, unknown>[] = [
    { id: "filename", header: "File", accessorFn: (r) => r.export.filename, cell: ({ row }) => <span className="font-mono text-[13px] font-medium">{row.original.export.filename}</span> },
    { id: "note", header: "Dispatch note", accessorFn: (r) => r.ref, cell: ({ row }) => <DispatchLink id={row.original.export.dispatchNoteId} reference={row.original.ref} /> },
    { id: "warehouse", header: "Warehouse", accessorFn: (r) => r.warehouse },
    { id: "rows", header: "Rows", accessorFn: (r) => r.export.rowCount, cell: ({ row }) => <span className="tabular">{row.original.export.rowCount}</span> },
    { id: "by", header: "Generated by", accessorFn: (r) => r.generatedByName },
    { id: "at", header: "Generated", accessorFn: (r) => r.export.generatedAt, cell: ({ row }) => <span className="tabular text-muted-foreground">{formatDateTime(row.original.export.generatedAt)}</span> },
    {
      id: "format",
      header: "Format",
      accessorFn: (r) => (r.export.isMockFormat ? "mock format" : "warehouse format"),
      cell: ({ row }) => (row.original.export.isMockFormat ? <Badge tone="outline" title="The warehouse's real file layout is not documented (UQ-12)">MOCK FORMAT</Badge> : <Badge tone="success">Warehouse format</Badge>),
    },
    {
      id: "actions",
      header: () => <span className="sr-only">Actions</span>,
      enableSorting: false,
      enableHiding: false,
      cell: ({ row }) => (
        <div className="flex justify-end gap-1" onClick={(e) => e.stopPropagation()}>
          <Button size="sm" variant="ghost" onClick={() => setPreview(row.original.export)} aria-label={`Preview ${row.original.export.filename}`}>
            <Eye /> Preview
          </Button>
          <Button size="sm" variant="secondary" onClick={() => downloadTextFile(row.original.export.filename, row.original.export.csv)} aria-label={`Download ${row.original.export.filename}`}>
            <FileDown /> CSV
          </Button>
        </div>
      ),
    },
  ];

  return (
    <RequirePermission permission="dispatch.view">
      <PageHeader
        title="Shipment files"
        description="The CSV the destination warehouse receives against. Generated from a Posted dispatch note; every generation is kept — history is never overwritten."
      />
      <div className="flex flex-col gap-4">
        <Callout tone="warning" title="Demo file layout (UQ-12)">
          The manuals say a shipment file is produced for the warehouse but do not list its columns. These files use a clearly flagged demo layout; the real
          warehouse format will replace it behind the shipment-export adapter.
        </Callout>
        <DataTable
          data-testid="shipments-table"
          aria-label="Shipment files"
          columns={columns}
          data={data ?? []}
          loading={isLoading}
          searchPlaceholder="Search file, note, warehouse…"
          emptyIcon={Warehouse}
          emptyTitle="No shipment files yet"
          emptyDescription="Post a dispatch note, then use Generate Shipment File."
          hidePagerWhenSinglePage
        />
      </div>

      <Dialog open={preview !== null} onOpenChange={(o) => !o && setPreview(null)}>
        <DialogContent size="xl">
          <DialogHeader>
            <DialogTitle className="font-mono text-sm">{preview?.filename}</DialogTitle>
            <DialogDescription>
              {preview?.rowCount} rows · generated {formatDateTime(preview?.generatedAt)} · demo format
            </DialogDescription>
          </DialogHeader>
          <DialogBody>
            <pre tabIndex={0} aria-label="Shipment file preview (scrollable)" className="max-h-96 overflow-auto rounded-xl bg-surface-secondary p-4 font-mono text-xs leading-5" data-testid="csv-preview">
              {preview?.csv}
            </pre>
          </DialogBody>
          <DialogFooter>
            <Button variant="secondary" onClick={() => setPreview(null)}>
              Close
            </Button>
            <Button onClick={() => preview && downloadTextFile(preview.filename, preview.csv)}>
              <FileDown /> Download CSV
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </RequirePermission>
  );
}
