"use client";

import { useState } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { AlertTriangle, ArrowRight, Landmark, Plus } from "lucide-react";
import {
  Badge,
  Button,
  Callout,
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
  DataTable,
  PageHeader,
  UnverifiedBadge,
  type ColumnDef,
} from "@tobacco/ui";
import { formatDate, formatDateTime, formatUsd, longDate, type PaymentSchedule } from "@tobacco/shared";
import { RequirePermission } from "@/components/page-guard";
import { StatusBadge } from "@/components/domain/status-badge";
import { PayBatchLink } from "@/components/domain/entity-links";
import { GenerateScheduleDialog } from "@/components/finance/generate-schedule-dialog";
import { formatMoney } from "@/components/finance/money";
import { PermissionButton } from "@/lib/permissions";
import { userName } from "@/mock/ctx";
import { useDb, useDbQuery } from "@/mock/hooks";
import { selectPayBatches, type PayBatchSummary } from "@/mock/domain/payments";

export default function PaymentsPage() {
  return (
    <RequirePermission permission="payments.view">
      <Inner />
    </RequirePermission>
  );
}

type ScheduleRow = PaymentSchedule & { generatedByName: string; lineCount: number; paidCount: number; totalCents: number };

function Inner() {
  const router = useRouter();
  const [open, setOpen] = useState(false);
  const [defaults, setDefaults] = useState<{ batchNo?: number; currency?: string; invoicesDate?: string } | undefined>();
  const local = useDb((db) => db.settings.localCurrencyCode);
  const { data, isLoading } = useDbQuery(["finance", "payments"], (db) => {
    const schedules: ScheduleRow[] = db.paymentSchedules
      .map((s) => {
        const lines = db.paymentLines.filter((l) => l.scheduleId === s.id);
        return {
          ...s,
          generatedByName: userName(db, s.generatedBy),
          lineCount: lines.length,
          paidCount: lines.filter((l) => l.status === "PAID").length,
          totalCents: lines.reduce((a, l) => a + l.amountCents, 0),
        };
      })
      .sort((a, b) => b.generatedAt.localeCompare(a.generatedAt));
    const excluded = db.paymentSchedules.flatMap((s) => s.excluded.map((e) => ({ ...e, ref: s.ref, payBatchNo: s.payBatchNo, currency: s.currency })));
    return { schedules, excluded, batches: selectPayBatches(db) };
  });

  const openGenerate = (d?: { batchNo?: number; currency?: string; invoicesDate?: string }) => {
    setDefaults(d);
    setOpen(true);
  };

  const columns: ColumnDef<ScheduleRow, unknown>[] = [
    { accessorKey: "ref", header: "Schedule", cell: ({ row }) => <Link href={`/finance/payments/${row.original.payBatchNo}`} className="font-mono text-[13px] font-medium text-primary hover:underline">{row.original.ref}</Link> },
    { accessorKey: "payBatchNo", header: "Pay batch", cell: ({ row }) => <PayBatchLink no={row.original.payBatchNo} /> },
    { accessorKey: "currency", header: "Currency" },
    { accessorKey: "status", header: "Status", cell: ({ getValue }) => <StatusBadge kind="paymentSchedule" value={getValue<string>()} /> },
    { id: "lines", header: "Paid / lines", accessorFn: (r) => `${r.paidCount}/${r.lineCount}`, cell: ({ row }) => <span className="tabular">{row.original.paidCount}/{row.original.lineCount}</span> },
    { accessorKey: "totalCents", header: "Total", cell: ({ row }) => <span className="tabular font-medium">{formatMoney(row.original.totalCents, row.original.currency)}</span> },
    { accessorKey: "invoicesDate", header: "Invoices date", cell: ({ getValue }) => formatDate(getValue<string>()) },
    { accessorKey: "generatedByName", header: "Generated by" },
    { accessorKey: "generatedAt", header: "Generated", cell: ({ getValue }) => <span className="tabular text-muted-foreground">{formatDateTime(getValue<string>())}</span> },
    { accessorKey: "isDemo", header: "", enableSorting: false, cell: ({ row }) => (row.original.isDemo ? <Badge tone="outline">demo history</Badge> : null) },
  ];

  const batchColumns: ColumnDef<PayBatchSummary, unknown>[] = [
    { accessorKey: "no", header: "Pay batch", cell: ({ row }) => <PayBatchLink no={row.original.no} /> },
    { accessorKey: "saleDate", header: "Sale date", cell: ({ getValue }) => longDate(getValue<string>()) },
    { accessorKey: "salesCount", header: "Sales" },
    { accessorKey: "growers", header: "Growers" },
    { accessorKey: "netUsdCents", header: "Net payout (USD)", cell: ({ getValue }) => <span className="tabular font-medium">{formatUsd(getValue<number>())}</span> },
    {
      id: "schedules",
      header: "Schedules",
      accessorFn: (b) => b.schedules.map((s) => s.currency).join(" "),
      cell: ({ row }) =>
        row.original.schedules.length === 0 ? (
          <Badge tone="warning" dot>None yet</Badge>
        ) : (
          <span className="flex flex-wrap gap-1.5">
            {row.original.schedules.map((s) => (
              <StatusBadge key={s.id} kind="paymentSchedule" value={s.status} className="whitespace-nowrap" />
            ))}
          </span>
        ),
    },
    {
      id: "actions",
      header: "",
      enableSorting: false,
      cell: ({ row }) => (
        <div className="flex justify-end gap-2" onClick={(e) => e.stopPropagation()}>
          <PermissionButton
            permission="payments.generate-schedule"
            size="sm"
            variant="secondary"
            onClick={() => openGenerate({ batchNo: row.original.no, invoicesDate: row.original.saleDate })}
            data-testid={`generate-for-${row.original.no}`}
          >
            Generate schedule
          </PermissionButton>
          <Button asChild size="sm" variant="ghost">
            <Link href={`/finance/payments/${row.original.no}`} aria-label={`Open pay batch ${row.original.no}`}>
              <ArrowRight />
            </Link>
          </Button>
        </div>
      ),
    },
  ];

  return (
    <>
      <PageHeader
        title="Grower payments"
        description="Generate a payment schedule per currency for each pay batch, export the bank file and record verified payment confirmations."
        actions={
          <PermissionButton permission="payments.generate-schedule" onClick={() => openGenerate()} data-testid="open-generate-schedule">
            <Plus /> Generate Payment Schedule
          </PermissionButton>
        }
      />
      <div className="flex flex-col gap-6">
        <Callout tone="warning" title="Nothing here moves money">
          Downloading a CSV doesn't mark growers as paid. CloudPay is a mock in this demo and sends nothing. A grower is Paid only when a verified bank or
          CloudPay confirmation (reference + exact amount) is recorded — and that is audited.
        </Callout>

        <section aria-label="Pay batches" className="flex flex-col gap-3">
          <h2 className="text-sm font-semibold">Pay batches</h2>
          <DataTable
            aria-label="Pay batches"
            data-testid="pay-batches-table"
            columns={batchColumns}
            data={data?.batches ?? []}
            loading={isLoading}
            emptyIcon={Landmark}
            emptyTitle="No pay batches yet"
            emptyDescription="A pay batch number is assigned when Stop Order Processing processes balanced sales."
            emptyAction={
              <Button asChild size="sm">
                <Link href="/finance/stop-order-processing">Stop Order Processing</Link>
              </Button>
            }
            hidePagerWhenSinglePage
            enableColumnVisibility={false}
            onRowClick={(b) => router.push(`/finance/payments/${b.no}`)}
          />
        </section>

        <section aria-label="Payment schedules" className="flex flex-col gap-3">
          <h2 className="text-sm font-semibold">Payment schedules</h2>
          <DataTable
            aria-label="Payment schedules"
            data-testid="schedules-table"
            columns={columns}
            data={data?.schedules ?? []}
            loading={isLoading}
            searchPlaceholder="Search schedule, batch, currency…"
            emptyIcon={Landmark}
            emptyTitle="No payment schedules"
            emptyDescription="Generate a schedule for a processed pay batch."
            initialColumnVisibility={{ isDemo: false }}
            hidePagerWhenSinglePage
          />
        </section>

        {data && data.excluded.length > 0 ? (
          <Card data-testid="excluded-growers">
            <CardHeader>
              <div>
                <CardTitle className="flex items-center gap-2">
                  <AlertTriangle className="size-4 text-warning-text" aria-hidden /> Growers left out of schedules
                </CardTitle>
                <CardDescription>Growers without bank details are left out of the file (Manual 08). Load their banking details and generate again.</CardDescription>
              </div>
            </CardHeader>
            <CardContent>
              <ul className="divide-y divide-border">
                {data.excluded.map((e) => (
                  <li key={`${e.ref}-${e.growerNo}`} className="flex flex-wrap items-center justify-between gap-3 py-2.5 text-sm">
                    <span>
                      <span className="font-mono text-[13px] font-medium">{e.growerNo}</span> · {e.name}
                      <span className="ml-2 text-muted-foreground">{e.reason} — {e.ref}</span>
                    </span>
                    <Button asChild variant="secondary" size="sm">
                      <Link href={`/growers/${e.growerNo}?tab=bank`}>Open bank details</Link>
                    </Button>
                  </li>
                ))}
              </ul>
            </CardContent>
          </Card>
        ) : null}

        <p className="flex flex-wrap items-center gap-2 text-xs text-muted-foreground">
          <UnverifiedBadge uq="UQ-04" /> How a grower's net is split between USD and {local} is not documented. <UnverifiedBadge uq="UQ-23" /> How payments are confirmed
          (and partial payments) is not documented.
        </p>
      </div>

      <GenerateScheduleDialog open={open} onOpenChange={setOpen} defaults={defaults} />
    </>
  );
}
